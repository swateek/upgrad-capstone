"""Advisory-reviewer agreement (plan §10.6, mentor B1.3): the verifier's model review against
reference labels on 30 answers. Offline: the review verdicts are in the runs' cards.

    uv run python -m eval.reviewer_agreement          # writes docs/results/reviewer-agreement.md

Sample: the answered planner-1 turns the reviewer checked; all wrong ones plus a seeded draw
from the right ones, 30 in all. Labels: docs/results/reviewer-labels.yaml (one S/U per working
sentence: does the cited source support it?). Agreement per sentence (accuracy, Cohen's kappa,
confusion) and per answer (any sentence unsupported).
"""

from __future__ import annotations

import json
import random
import re
from pathlib import Path

import yaml

from customs.config import PROJECT_ROOT

RUN = "planner-1"
N, SEED = 30, 106
LABELS = PROJECT_ROOT / "docs" / "results" / "reviewer-labels.yaml"
OUT = PROJECT_ROOT / "docs" / "results" / "reviewer-agreement.md"
CITED = re.compile(r"\(([^()]*(?:\([^()]*\)[^()]*)*)\)\.?$")


def sample(run: str = RUN) -> list[dict]:
    rows = []
    path = PROJECT_ROOT / "docs" / "results" / "runs" / run / "raw.jsonl"
    for line in path.read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        for t in r["turns"]:
            if "checked" in (t["card"]["meta"].get("review") or {}):
                rows.append((r, t))
    wrong = [x for x in rows if not x[1]["correct"]]
    right = [x for x in rows if x[1]["correct"]]
    pick = wrong + random.Random(SEED).sample(right, N - len(wrong))
    pick.sort(key=lambda x: (x[0]["id"], x[1]["turn"]))
    out = []
    for r, t in pick:
        c = t["card"]
        flagged = set(c["meta"]["review"]["unsupported"])
        sents = []
        for i, w in enumerate(c["working"], start=1):
            m = CITED.search(w)
            sents.append({"i": i, "text": w, "cited": m.group(1) if m else "",
                          "reviewer": "U" if i in flagged else "S"})  # fmt: skip
        out.append({"key": f"{r['id']}-{t['turn']}", "correct": t["correct"],
                    "category": r["category"], "sentences": sents})  # fmt: skip
    return out


def kappa(a: list[str], b: list[str]) -> float:
    n = len(a)
    po = sum(x == y for x, y in zip(a, b, strict=True)) / n
    pe = sum((a.count(k) / n) * (b.count(k) / n) for k in ("S", "U"))
    return (po - pe) / (1 - pe) if pe < 1 else 1.0


def agreement(answers: list[dict], labels: dict) -> dict:
    rev, ref = [], []
    per_answer = []
    for a in answers:
        lab = labels[a["key"]]["labels"]
        if len(lab) != len(a["sentences"]):
            raise ValueError(f"{a['key']}: {len(lab)} labels for {len(a['sentences'])} sentences")
        r = [s["reviewer"] for s in a["sentences"]]
        rev += r
        ref += list(lab)
        per_answer.append(("U" in r, "U" in lab))
    conf = {(x, y): sum(1 for p, q in zip(rev, ref, strict=True) if (p, q) == (x, y))
            for x in "SU" for y in "SU"}  # fmt: skip
    caught = conf[("U", "U")] / max(1, conf[("U", "U")] + conf[("S", "U")])
    precise = conf[("U", "U")] / max(1, conf[("U", "U")] + conf[("U", "S")])
    return {"sentences": len(rev), "accuracy": sum(p == q for p, q in zip(rev, ref, strict=True))
            / len(rev), "kappa": kappa(rev, ref), "confusion": conf,
            "recall_unsupported": caught, "precision_unsupported": precise,
            "answers": len(per_answer),
            "answer_accuracy": sum(p == q for p, q in per_answer) / len(per_answer)}  # fmt: skip


def report(answers: list[dict], doc: dict) -> str:
    labels, g = doc["answers"], agreement(answers, doc["answers"])
    c = g["confusion"]
    who = (f"Labels drafted by {doc['drafted_by']} and reviewed by {doc['reviewed_by']}."
           if doc.get("reviewed_by") else
           f"**Labels drafted by {doc['drafted_by']}; not yet reviewed by a person.**")  # fmt: skip
    lines = [
        "# Advisory reviewer agreement (plan §10.6)", "",
        (f"Generated by `eval/reviewer_agreement.py`. {g['answers']} answers from `{RUN}` "
         f"({g['sentences']} sentences), all wrong answers the reviewer checked plus a seeded "
         "sample of right ones. Question per sentence: does the cited source support it? "
         f"{who} Rules for a label: `docs/results/reviewer-labels.yaml`."), "",
        "| measure | value |", "|---|---|",
        f"| sentences in agreement | {g['accuracy']:.1%} |",
        f"| Cohen's kappa | {g['kappa']:.2f} |",
        f"| unsupported sentences the reviewer caught (recall) | {g['recall_unsupported']:.1%} |",
        f"| reviewer's 'unsupported' that were right (precision) | {g['precision_unsupported']:.1%} |",
        f"| answers in agreement (any sentence unsupported) | {g['answer_accuracy']:.1%} |", "",
        "| | label S | label U |", "|---|---|---|",
        f"| reviewer S | {c[('S', 'S')]} | {c[('S', 'U')]} |",
        f"| reviewer U | {c[('U', 'S')]} | {c[('U', 'U')]} |", "",
        "## Sentences", "",
        "| answer | # | sentence | reviewer | label | why |", "|---|---|---|---|---|---|",
    ]  # fmt: skip
    for a in answers:
        lab, why = labels[a["key"]]["labels"], labels[a["key"]].get("why") or {}
        for s, x in zip(a["sentences"], lab, strict=True):
            mark = "" if s["reviewer"] == x else " **≠**"
            text = s["text"].replace("|", "/")
            lines.append(f"| {a['key']}{'' if a['correct'] else ' (wrong)'} | {s['i']} | {text} "
                         f"| {s['reviewer']} | {x}{mark} | {why.get(s['i'], '')} |")  # fmt: skip
    return "\n".join(lines) + "\n"


def main(labels: Path = LABELS, out: Path = OUT) -> None:
    doc = yaml.safe_load(labels.read_text(encoding="utf-8"))
    answers = sample()
    missing = [a["key"] for a in answers if a["key"] not in doc["answers"]]
    if missing:
        raise SystemExit(f"no labels for {missing}")
    text = report(answers, doc)
    out.write_text(text, encoding="utf-8")
    print("\n".join(text.splitlines()[:16]))


if __name__ == "__main__":
    main()
