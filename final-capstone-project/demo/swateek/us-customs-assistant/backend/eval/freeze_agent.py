"""Prompt freeze (plan step 10): lock the agent as tuned on dev before the official runs.

    uv run python -m eval.freeze_agent --version 1 --dev-run dev-05

Writes pack/agent.lock.yaml: sha256 of every file that decides the agent's behaviour: the agent
prompts, the guard policy, the agent code, search and query building, and the calculators and
tools (the code checks added while tuning on dev are part of what was tuned). tests/
test_agent_freeze.py fails, by file name, if any of them changes. A change after the freeze
needs a version bump and a written reason in docs/results/dev-runs.md.
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
from datetime import UTC, datetime

import yaml

from customs.config import PROJECT_ROOT

LOCK = PROJECT_ROOT / "pack" / "agent.lock.yaml"
GLOBS = [
    "pack/prompts/agent_intake.md",
    "pack/prompts/planner.md",
    "pack/prompts/writer.md",
    "pack/prompts/tool_executor.md",
    "pack/prompts/single_rag.md",
    "pack/policy/*.yaml",
    "backend/src/customs/agent/*.py",
    "backend/src/customs/retrieval/service.py",
    "backend/src/customs/retrieval/query.py",
    "backend/src/customs/tools/*.py",
]


def frozen_files() -> list[str]:
    out = []
    for g in GLOBS:
        out += sorted(str(p.relative_to(PROJECT_ROOT)) for p in PROJECT_ROOT.glob(g))
    return out


def sha(rel: str) -> str:
    return hashlib.sha256((PROJECT_ROOT / rel).read_bytes()).hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version", type=int, required=True)
    ap.add_argument("--dev-run", required=True, help="the dev run the freeze is based on")
    a = ap.parse_args()
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], check=True, capture_output=True,
                            text=True, cwd=PROJECT_ROOT).stdout.strip()  # fmt: skip
    doc = {
        "version": a.version,
        "frozen_on": datetime.now(UTC).date().isoformat(),
        "base_commit": commit,
        "dev_run": a.dev_run,
        "files": {rel: sha(rel) for rel in frozen_files()},
    }
    header = (
        f"# Agent freeze, version {a.version}. Generated by eval.freeze_agent; do not hand-edit.\n"
        "# tests/test_agent_freeze.py fails if any listed file changes. To change one: bump the\n"
        "# version, regenerate, and write the reason in docs/results/dev-runs.md.\n"
    )
    LOCK.write_text(header + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    print(f"wrote {LOCK} ({len(doc['files'])} files)")


if __name__ == "__main__":
    main()
