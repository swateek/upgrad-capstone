"""Build gold-v2: eval-v2's 80 questions re-scored under SPEC v2, plus errata.

    uv run python eval/build_gold_v2.py prepare    # scenarios.yaml + gold_v2_changes.yaml -> scenarios_gold_v2.yaml
    uv run python eval/build_gold_v2.py workbook   # -> gold_v2.xlsx (formulas)
    soffice --headless --convert-to xlsx --outdir /tmp eval/gold_v2.xlsx && cp /tmp/gold_v2.xlsx eval/
    uv run python eval/build_gold_v2.py export     # -> eval_set_gold_v2.jsonl, gold_v2.md
    uv run python eval/build_gold_v2.py diff       # only the listed ids differ from gold-v1
    uv run python eval/build_gold_v2.py review     # -> REVIEW_GOLD_V2.md (the owner's check)

eval/scenarios.yaml and eval/eval_set.jsonl (gold-v1, tag eval-v2) are read, never written:
agent v1's official result stays scored against them. The dollars come from eval/build_eval.py's
spreadsheet formulas, never from src/tools (rule 5). Results on gold-v2 are labelled as such:
these questions informed the agent v2 fixes, so eval-v3 is the headline set for agent v2.
"""

from __future__ import annotations

import csv
import json
import random
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_eval

SOURCE = HERE / "scenarios.yaml"
GOLD_V1 = HERE / "eval_set.jsonl"
CHANGES = HERE / "gold_v2_changes.yaml"
SCENARIOS = HERE / "scenarios_gold_v2.yaml"
OUT = {"eval": HERE / "eval_set_gold_v2.jsonl"}
PASSES = HERE.parent / "results" / "runs" / "official-planner-1" / "scores_planner.csv"
SEED = 20261123
SAMPLE_SIZE = 12  # 20% of the 60 Day 10 passes


def changes() -> list[dict]:
    return yaml.safe_load(CHANGES.read_text())["changes"]


def prepare() -> None:
    items = [
        s for s in yaml.safe_load(SOURCE.read_text())["scenarios"] if s["set"] == "eval"
    ]
    if len(items) != 80:
        raise SystemExit(f"expected 80 eval-v2 scenarios, found {len(items)}")
    by_id = {s["id"]: s for s in items}
    for c in changes():
        s = by_id[c["id"]]
        for n, patch in (c.get("basket") or {}).items():
            s["basket"][int(n) - 1].update(patch)
        for k, v in (c.get("gold") or {}).items():
            s["gold"][k] = v
        s["gold_v2_change"] = c["rule"]
    SCENARIOS.write_text(
        "# Generated by eval/build_gold_v2.py prepare from scenarios.yaml + gold_v2_changes.yaml.\n"
        "# Do not edit: change gold_v2_changes.yaml and rebuild.\n"
        + yaml.safe_dump({"scenarios": items}, sort_keys=False, allow_unicode=True)
    )
    print(f"wrote {SCENARIOS.name}: 80 scenarios, {len(changes())} changed")


def point_build_eval() -> list[dict]:
    """Aim the eval-v2 gold machinery at the gold-v2 files."""
    build_eval.SCENARIOS = SCENARIOS
    build_eval.WORKBOOK = HERE / "gold_v2.xlsx"
    build_eval.OUT = OUT
    build_eval.MARKDOWN = HERE / "gold_v2.md"
    return yaml.safe_load(SCENARIOS.read_text())["scenarios"]


def read(path: Path) -> dict[str, dict]:
    return {r["id"]: r for r in map(json.loads, path.open())}


def diff() -> int:
    """Every gold difference from gold-v1; fails if an unlisted id moved."""
    v1, v2 = read(GOLD_V1), read(OUT["eval"])
    listed = {c["id"] for c in changes()}
    bad = 0
    for i in v1:
        a, b = v1[i], v2[i]
        if a == b:
            continue
        moved = [k for k in a["gold"] if a["gold"][k] != b["gold"].get(k)]
        other = [k for k in a if k != "gold" and a[k] != b.get(k)]
        tag = "listed" if i in listed else "NOT LISTED"
        bad += i not in listed
        print(
            f"{i} ({tag}): gold fields {moved}" + (f", other {other}" if other else "")
        )
        for k in moved:
            if k != "lines":
                print(f"    {k}: {a['gold'][k]} -> {b['gold'].get(k)}")
    missing = listed - {i for i in v1 if v1[i] != v2[i]}
    if missing:
        print(f"listed but unchanged: {sorted(missing)}")
    print("ok" if not bad else f"{bad} unlisted ids moved")
    return 1 if bad else 0


# Drawn on 2026-11-23 from the 60 Day 10 passes, leaving out E07/E47 (seed 20261123), and checked
# by the owner. Fixed here so later metadata changes cannot redraw it.
REVIEW_SAMPLE = [
    "E08",
    "E14",
    "E15",
    "E32",
    "E40",
    "E43",
    "E44",
    "E49",
    "E57",
    "E66",
    "E71",
    "E77",
]


def draw_sample() -> list[str]:
    """How REVIEW_SAMPLE was drawn (kept so the draw can be repeated)."""
    passed = sorted(
        r["id"] for r in csv.DictReader(PASSES.open()) if r["correct"] == "True"
    )
    pool = [i for i in passed if i not in ("E07", "E47")]
    return sorted(random.Random(SEED).sample(pool, SAMPLE_SIZE))


def review() -> None:
    v1, v2 = read(GOLD_V1), read(OUT["eval"])
    sc = {s["id"]: s for s in yaml.safe_load(SCENARIOS.read_text())["scenarios"]}

    def gold_line(g: dict) -> list[str]:
        out = [f"{g['outcome']}" + (f" ({g['reason']})" if g.get("reason") else "")]
        if g.get("exemption"):
            out.append(f"exemption {g['exemption']}")
        if g.get("bottom_line"):
            out.append(f"bottom line {[b['type'] for b in g['bottom_line']]}")
        if g.get("clarify_facts"):
            out.append(f"asks {g['clarify_facts']}")
        if g.get("state_flag"):
            out.append(f"state flag {g['state_flag']}")
        text = ", ".join(out)
        if g.get("total_usd") is not None:
            text += f"; duty ${g['duty_usd']:.2f} + excise ${g['excise_usd']:.2f} = **${g['total_usd']:.2f}**"
        if g.get("whatif"):
            text += f"; what-if {g['whatif']['max_units']} units, owing ${g['whatif']['owed_usd']:.2f}"
        return [text]

    def fmt(i: str, changed: bool) -> str:
        r, s = v2[i], sc[i]
        out = [f"### {i} ({r['type']})", "", f"> {r['question']}", ""]
        prof = {
            k: v
            for k, v in (r["facts"] or {}).get("profile", {}).items()
            if v is not None
        }
        if prof:
            out.append(f"- **Facts:** {prof}")
        for n, b in enumerate(s.get("basket") or [], 1):
            q = b.get("quantity") or {}
            extra = ", ".join(
                f"{k} {b[k]}"
                for k in (
                    "unit_ml",
                    "count",
                    "abv",
                    "unit_price_usd",
                    "origin",
                    "bought_where",
                    "excise_class",
                    "gold_exempt_l",
                )
                if b.get(k) is not None
            )
            out.append(
                f"  - line {n}: {q.get('value')} × {q.get('unit')} {b['item']}, {extra}"
            )
        if inj := s.get("inject_into_retrieval"):
            out.append(f'- **Planted document** `{inj["doc_id"]}`: "{inj["text"]}"')
        if changed:
            out.append(f"- **gold-v1:** {gold_line(v1[i]['gold'])[0]}")
            out.append(f"- **gold-v2:** {gold_line(r['gold'])[0]}")
            out.append(f"- **Why:** {s['gold_v2_change']}")
        else:
            out.append(f"- **Gold (v1 = v2):** {gold_line(r['gold'])[0]}")
        if r["gold"].get("must_not_contain"):
            out.append(f"- **Must not say:** {r['gold']['must_not_contain']}")
        if r["gold"].get("citations"):
            out.append(f"- **Must cite:** {', '.join(r['gold']['citations'])}")
        out.append("- **Your verdict:** ☐ right ☐ wrong: ______")
        return "\n".join(out) + "\n"

    changed = [c["id"] for c in changes() if c.get("scored", True)]
    meta = [c["id"] for c in changes() if not c.get("scored", True)]
    picked = REVIEW_SAMPLE
    doc = [
        "# gold-v2 check (owner)",
        "",
        (
            "Check each against the regulation and SPEC v2 (docs/SPEC.md 9b), not against the agent. "
            "Tick right or wrong; for a wrong one, say what the rule gives. Wrong ones go into "
            "`eval/gold_v2_changes.yaml` with the rule, and the build is re-run."
        ),
        "",
        (
            f"Part 1: the {len(changed)} changed scenarios, gold-v1 next to gold-v2. "
            f"Part 2: {len(picked)} of the 60 Day 10 passes drawn at random (seed {SEED}): a pass "
            "can hide a gold error the agent shares. The 20 failures were read on Day 10. How the "
            "80 were screened is at the top of `eval/gold_v2_changes.yaml`."
        ),
        "",
        "## Part 1: changed",
        "",
        *[fmt(i, True) for i in changed],
        "## Part 2: random sample of passes",
        "",
        *[fmt(i, i in meta) for i in picked],
        "## Part 3: metadata only (not scored)",
        "",
        (
            "The exemption filled in where every line is prohibited, as eval-v3 does "
            "(`score.py` does not read it). Added at the owner's request after the check."
        ),
        "",
        *[fmt(i, True) for i in meta if i not in picked],
    ]
    (HERE / "REVIEW_GOLD_V2.md").write_text("\n".join(doc))
    print(
        f"wrote REVIEW_GOLD_V2.md: {len(changed)} changed, {len(picked)} sampled passes"
    )


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) == 2 else ""
    if cmd == "prepare":
        prepare()
    elif cmd == "workbook":
        build_eval.build_workbook(point_build_eval())
    elif cmd == "export":
        build_eval.export(point_build_eval())
    elif cmd == "diff":
        return diff()
    elif cmd == "review":
        review()
    else:
        raise SystemExit(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
